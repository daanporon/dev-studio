// ds.ts — the `ds` dispatcher (Bun); bin/ds is the front door. Every bin/commands/<name>.ts is
// a subcommand (found by glob, so a unit adds one without touching this file, KTD14) exporting
//   export const help = "<args> — <what it does>";
//   export async function run(args: string[]): Promise<number | void>;   // the exit code
// U185: `ds <name>` also runs a shell script from any purpose folder under bin/
// (commands/, role/, review/, hooks/, board/, host/, lib/, loop/, backend/):
// `<folder>/<name>.sh` with the arguments passed through and its exit code returned.
// Two files with one name in different folders are a collision (a test fails on it);
// dispatch refuses a colliding name. `ds help` lists every command by folder with its
// one-line purpose (the `help` export for .ts, the first header comment line for .sh);
// `ds help --markdown` prints bin/README.md.
// A global `--state <root>` sets DS_STATE_ROOT before the command opens the store.
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

const BIN = import.meta.dir;
const FOLDERS = ["commands", "role", "review", "hooks", "board", "host", "lib", "loop", "backend"] as const;

type Entry = { name: string; folder: string; file: string; kind: "ts" | "sh" | "ts-file" };

export function scanBin(binDir: string): Entry[] {
  const out: Entry[] = [];
  for (const folder of FOLDERS) {
    const dir = join(binDir, folder);
    if (!existsSync(dir)) continue;
    for (const f of readdirSync(dir).sort()) {
      const file = join(dir, f);
      if (folder === "commands" && f.endsWith(".ts")) out.push({ name: f.slice(0, -3), folder, file, kind: "ts" });
      else if (f.endsWith(".sh")) out.push({ name: f.slice(0, -3), folder, file, kind: "sh" });
      else if (folder === "board" && f.endsWith(".ts")) out.push({ name: f.slice(0, -3), folder, file, kind: "ts-file" });
      else if (folder === "loop" && f === "main.ts") out.push({ name: "main", folder, file, kind: "ts-file" });
    }
  }
  return out;
}

export function collisions(entries: Entry[]): Map<string, Entry[]> {
  const by = new Map<string, Entry[]>();
  for (const e of entries) by.set(e.name, [...(by.get(e.name) ?? []), e]);
  return new Map([...by].filter(([, v]) => v.length > 1));
}

function shPurpose(file: string): string {
  try {
    for (const line of readFileSync(file, "utf8").split("\n").slice(0, 12)) {
      const m = line.match(/^#\s+(.+)$/);
      if (m && !m[1].startsWith("shellcheck") && !m[1].startsWith("!")) return m[1].trim();
    }
  } catch { /* unreadable: no purpose */ }
  return "";
}

async function purpose(e: Entry): Promise<string> {
  if (e.kind === "ts") {
    try { return ((await import(e.file)).help as string) ?? ""; } catch { return ""; }
  }
  if (e.kind === "ts-file") {
    try {
      for (const line of readFileSync(e.file, "utf8").split("\n").slice(0, 4)) {
        const m = line.match(/^\/\/\s+(.+)$/);
        if (m) return m[1].trim();
      }
    } catch { /* ignore */ }
    return "";
  }
  return shPurpose(e.file);
}

export async function helpLines(binDir: string): Promise<{ folder: string; name: string; purpose: string; rel: string }[]> {
  const rows = [];
  for (const e of scanBin(binDir)) rows.push({ folder: e.folder, name: e.name, purpose: await purpose(e), rel: `bin/${e.folder}/${e.name}${e.kind === "sh" ? ".sh" : ".ts"}` });
  return rows.sort((a, b) => a.folder.localeCompare(b.folder) || a.name.localeCompare(b.name));
}

// A purpose with <s>, <who> and the like reads as HTML on GitHub (`<s>` strikes the rest of the
// page through), so it goes in a code span; a backtick inside widens the fence.
export function codeSpan(text: string): string {
  if (!/[<>]/.test(text)) return text;
  const fence = "`".repeat(Math.max(0, ...(text.match(/`+/g) ?? []).map((r) => r.length)) + 1);
  const pad = text.startsWith("`") || text.endsWith("`") ? " " : "";
  return `${fence}${pad}${text}${pad}${fence}`;
}

export async function markdown(binDir: string): Promise<string> {
  const rows = await helpLines(binDir);
  const lines = [
    "# bin/ — every script behind `ds`",
    "",
    "Generated by `bin/ds help --markdown`; do not edit by hand. `bin/ds`, `bin/ds.ts` and this README stay at the top; everything else sits in a folder named by purpose.",
    "",
  ];
  for (const folder of FOLDERS) {
    const inFolder = rows.filter((r) => r.folder === folder);
    if (!inFolder.length) continue;
    lines.push(`## ${folder}`, "");
    for (const r of inFolder) lines.push(`- \`ds ${r.name}\` — ${codeSpan(r.purpose)} (\`${r.rel}\`)`);
    lines.push("");
  }
  return lines.join("\n");
}

const argv = process.argv.slice(2);
// side-loop-host U7 (KTD5): on a side host a worker's terminal carries DS_MAIN_URL. Every call but help and the
// forward table's `local` commands goes to main through the side loop's relay, --state and all (main refuses it).
// U8: a `split` command first reads what it needs from this worktree here and sends those facts along.
const mainUrl = process.env.DS_MAIN_URL;
if (mainUrl && !process.env.DS_LINK_FORWARDED && argv[0] && !["help", "--help", "-h"].includes(argv[0])) {
  const { kindFor } = await import("./link/forward-table.ts");
  const { parseMember } = await import("./loop/core/whoami.ts");
  const kind = kindFor(parseMember(process.env.DS_MEMBER)?.role ?? "", argv);
  if (kind !== "local") {
    const { forwardDs } = await import("./link/relay.ts");
    const facts = kind === "split" ? await (await import("./link/split.ts")).gather(argv[0], argv.slice(1)) : undefined;
    process.exit(await forwardDs(mainUrl, argv, process.env, facts));
  }
}
const at = argv.indexOf("--state");
if (at >= 0) {
  if (!argv[at + 1]) { console.error("ds: --state needs a directory"); process.exit(2); }
  process.env.DS_STATE_ROOT = argv[at + 1];
  argv.splice(at, 2);
}
const [name, ...args] = argv;

if (!name || name === "help" || name === "--help" || name === "-h") {
  if (args.includes("--markdown")) { process.stdout.write(await markdown(BIN)); process.exit(0); }
  const rows = await helpLines(BIN);
  const lines: string[] = ["usage: ds [--state <root>] <command> [args]", ""];
  for (const folder of FOLDERS) {
    const inFolder = rows.filter((r) => r.folder === folder);
    if (!inFolder.length) continue;
    lines.push(`${folder}:`);
    for (const r of inFolder) lines.push(`  ${r.name} — ${r.purpose}`);
  }
  console.error(lines.join("\n"));
  process.exit(name ? 0 : 2);
}

const entries = scanBin(BIN);
const dup = collisions(entries).get(name);
if (dup) { console.error(`ds: command '${name}' is in more than one folder: ${dup.map((d) => d.file).join(", ")}`); process.exit(2); }
const entry = entries.find((e) => e.name === name && e.kind !== "ts-file");
if (!entry) { console.error(`ds: no command '${name}' (ds help)`); process.exit(2); }
if (entry.kind === "sh") {
  const r = Bun.spawnSync([entry.file, ...args], { stdout: "inherit", stderr: "inherit", stdin: "inherit" });
  process.exit(r.exitCode ?? 1);
}
try {
  const code = await (await import(entry.file)).run(args);
  process.exit(typeof code === "number" ? code : 0);
} catch (e) {
  console.error(`ds ${name}: ${(e as Error).message}`);
  process.exit(1);
}
